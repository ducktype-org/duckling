namespace compiler::helios {
	/**
	 * @brief The unique ID of a symbol that is always increasing.
	 *
	 * The SymbolID should use this ID to implement its queryUnstablePerfectHash  so that it always
	 * generates a unique ID for each symbol. The previous approach of using the pointer to the
	 * SymbolData in cache was not working, because when we deallocate a SymbolData (LS can do that)
	 * some new SymbolData can be allocated at the same address.
	 */
	STRONG_TYPEDEF_ID(SymbolDataID);

	/**
	 * Symbol data shared by all symbols.
	 */
	struct CommonSymbolData final {
		/**
		 * Symbol name.
		 *
		 * @note In the future there might also be anonymous symbols (symbols with no name), like:
		 * `let _ = 5;`, lambdas, `using a.*`, etc.
		 * For now, we work around it, as all things that could be anonymous are also a wildcard.
		 * Those symbols will also need to have mangled name.
		 */
		base::StrID name;

		/**
		 * Symbol kind, determines what kind of symbol it is.
		 */
		SymbolKind kind;

		/** Whether the symbol is a dependent symbol.
		 * Dependent symbols are symbols that can't be used in actual execution without some
		 * context, e.g. class fields.
		 */
		bool dependent = false;

		/**
		 * When this is true, the symbol is ignored by the lookup.
		 */
		bool is_ignored_by_lookup = false;

		/**
		 * List of attributes on a symbol.
		 */
		std::vector<Attribute> attributes = {};
	};

	/**
	 * @brief Symbol data of symbols that are created from PST elements.
	 */
	struct PstSymbolData final {
		/**
		 * Scope in which the symbol was defined.
		 */
		ScopeID scope;

		/**
		 * Hash of the PST element that the symbol was created from.
		 */
		pst::HashType pst_element_hash;

		/**
		 * Return associated pst_element.
		 */
		[[nodiscard]] pst::AccessLocked<pst::LangElement> getElement() const {
			return pst::LangElement::getByStableHash(pst_element_hash);
		}
	};

	/**
	 * @brief Symbol data of members of a type, i.e. fields, methods, constructors and destructors,
	 * either declared in a class body or generated by the compiler.
	 */
	struct TypeMemberData final {
		/**
		 * Type the symbol is a member of.
		 */
		tsh::AbstractType owner_type;
	};

	/**
	 * @brief Symbol data of the declaration of a baked template, i.e. the inner statement of a
	 * template instantiated with concrete template arguments.
	 */
	struct TemplateInstanceData final {
		/**
		 * The template the symbol was baked from.
		 */
		SymID template_symbol;

		/**
		 * The constants holding the template arguments, matching the template parameters 1-1.
		 */
		std::vector<SymID> template_arguments_symbols;
	};

	/**
	 * @brief Symbol data of compiler builtins, i.e. PST `fundecl`s carrying a `@builtin("...")`
	 * attribute and the generated `defgen::BuiltinTemplatedSymbol`s. The implementation is
	 * provided by the compiler (see `getBuiltinImpl`) rather than from a body in the source.
	 */
	struct BuiltinData final {
		/**
		 * Which builtin this symbol implements.
		 */
		BuiltinKind builtin;
	};

	/**
	 * @brief Stores generic symbol data.
	 *
	 * The data is split into independent optional parts, so a symbol can be e.g. a builtin template
	 * instance or a template instance member of a type at the same time:
	 * - `maybe_pst_data` is set for the symbols created from a PST element,
	 * - `maybe_type_member_data` for the members of a type, declared in the PST or generated,
	 * - `maybe_template_instance_data` for the declarations of baked templates,
	 * - `maybe_builtin_data` for the symbols implemented by the compiler,
	 * - `maybe_generated_data` for the symbols generated by the compiler.
	 *
	 * Exactly one of `maybe_pst_data` and `maybe_generated_data` is set.
	 *
	 * @note Symbols and their associated SymbolData are created by HELIOS via queries.
	 * SymbolData is by design a "read-only" structure.
	 */
	struct SymbolData final {
		CommonSymbolData                                   common_data;
		base::Optional<PstSymbolData>                      maybe_pst_data               = {};
		base::Optional<TypeMemberData>                     maybe_type_member_data       = {};
		base::Optional<TemplateInstanceData>               maybe_template_instance_data = {};
		base::Optional<BuiltinData>                        maybe_builtin_data           = {};
		base::Optional<defgen::GeneratedSymbolDataVariant> maybe_generated_data         = {};
		SymbolDataID                                       id = SymbolDataID::next();

		/**
		 * @brief Make the data of a compiler generated symbol, deducing its kind and owner type
		 * from @p generated_data.
		 */
		static SymbolData makeGeneratedSymbolData(
			base::StrID name, defgen::GeneratedSymbolDataVariant generated_data
		);

		[[nodiscard]]
		base::Optional<ScopeID> getScope() const;

		template<class T>
		[[nodiscard]]
		CRef<T> getGeneratedData() const {
			auto data = getGeneratedDataOpt<T>();
			CORE_ASSERT(
				data.has_value(),
				"SymbolData does not hold the requested generated data. ",
				"Symbol: ",
				common_data.name.strView(),
				" Requested type: ",
				typeid(T).name()
			);
			return data.value();
		}

		template<class T>
		[[nodiscard]]
		base::Optional<CRef<T>> getGeneratedDataOpt() const {
			if (not maybe_generated_data.has_value()) return std::nullopt;
			if (auto ptr = std::get_if<T>(&maybe_generated_data.value())) return CRef<T>{ ptr };
			return std::nullopt;
		}

		/**
		 * @brief Whether the symbol was created from a PST element written by the user and is
		 * implemented by it, i.e. it is not a builtin.
		 */
		[[nodiscard]]
		bool isPstImplemented() const;

		[[nodiscard]]
		base::Optional<pst::AccessLocked<pst::LangElement>> maybePstElement() const;

		/**
		 * Return associated pst_element cast to Stmt.
		 * Panics if element is not a statement or if symbol is not associated with PST element.
		 */
		[[nodiscard]]
		base::Optional<pst::Access<pst::Stmt>> stmtCast(query::Context& ctx) const;
	};

	/**
	 * @brief Helper struct used to access private SymID data.
	 * It is used by HELIOS only. It is a struct so SymID can friend it.
	 */
	struct GetSymRef_Functor final {
		static auto get(const SymID id) { return id.ref; }

		static SymID make(const CRef<SymbolData> ref) { return SymID{ ref }; }
	};

	inline auto getSymRef(const SymID id) { return GetSymRef_Functor::get(id); }
}
