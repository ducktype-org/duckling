	/**
	 * @brief Structure representing a place (L-value) in the generated DVM bytecode (which includes
	 both locals and globals).
	 *
	 * This structure is an abstraction layer over a place in generated bytecode. Place in DVM can
	 * either mean:
	 * - Direct reference to a local stack variable - for which the AccessKind field will be set to
	 *  Direct.
	 * - Direct reference to a global variable - for which the AccessKind field will be set to
	 * Direct.
	 * - A pointer to the place - for which the AccessKind field will be set to `Pointer`. This
	 * handles cases like:
	 * 		- some_int_reference = 123 - DVMPlace stores a local variable storing a pointer to the
	 * 		  original address that the reference stores.
	 * 		- class.field = 123 - DVMPlace stores a local variable storing a pointer to the exact
	 * offset at which the `field` is located in `class`.
	 * 		- array[3] = 123 - DVMPlace stores a local variable storing a pointer to the exact
	 * offset at which the third element of the array is located.
	 *
	 * If the access kind is set to `Direct`, a load into the place will be performed by `mov_X_X`.
	 * If the access kind is set to `Pointer`, a load into the place will be performed by
	 * `store_pptr_pany`.
	 * If the access kind is set to `DynTablePointer`, a load into the place will be performed by
	 * `dynTableStore_pptr_pany_p64`.
	 * If the access kind is set to `CPointer`, a load into the place will be performed by
	 * `store_pcptr_pany`.
	 */
	class DVMPlace {
	public:
		enum class AccessKind : uint8_t { Direct, Pointer, DynTablePointer, CPointer };

		/**
		 * Some places have special meaning, like ReturnValue, knowing this allows for
		 * better codegen (for example in return instruction).
		 *
		 * The `ConditionTmp` kind is not currently used.
		 */
		enum class SpecialKind : uint8_t { ReturnValue, ConditionTmp, Normal };

		/**
		 * @param declaration The declaration of the place's type, which picks the operand kind
		 * its contents need. Absent for a pointer, which is written rather than declared.
		 */
		DVMPlace(
			base::StrID                                name,
			vm::code::TypeExpr                         expr,
			base::Optional<CRef<vm::code::TypeOfData>> declaration,
			AccessKind                                 access_kind,
			SpecialKind                                special_kind = SpecialKind::Normal
		);

		bool operator==(const DVMPlace& other) const = default;
		operator vm::opargs::OpCodeArg() const;

		[[nodiscard]] bool isDirect() const { return access_kind == AccessKind::Direct; }

		[[nodiscard]] AccessKind getAccessKind() const { return access_kind; }

		/// @brief What this place's type is written as, which every place has.
		[[nodiscard]] vm::code::TypeExpr getTypeExpr() const { return expr; }

		[[nodiscard]] DVMPlace withAccessKind(AccessKind kind) const {
			return { name, expr, operand_kind, kind, special_kind };
		}

		[[nodiscard]] DVMPlace withSpecialKind(SpecialKind special) const {
			return { name, expr, operand_kind, access_kind, special };
		}

		[[nodiscard]] SpecialKind getSpecialKind() const { return special_kind; }

		[[nodiscard]] vm::opargs::OpCodeArg asArgument() const;
		[[nodiscard]] vm::opargs::OpCodeArg asAnyArgument() const;

	private:
		/// @brief The typed operand a place is passed as.
		enum class OperandKind : uint8_t {
			Place8,
			Place16,
			Place32,
			Place64,
			FixedSizeTable,
			Structure,
			Variant,
			Opaque,
			Pointer,
			CPointer,
			Unsupported
		};

		DVMPlace(
			base::StrID        name,
			vm::code::TypeExpr expr,
			OperandKind        operand_kind,
			AccessKind         access_kind,
			SpecialKind        special_kind
		):
			  name(name),
			  expr(expr),
			  operand_kind(operand_kind),
			  access_kind(access_kind),
			  special_kind(special_kind) {}

		base::StrID        name;
		vm::code::TypeExpr expr;
		OperandKind        operand_kind;
		AccessKind         access_kind;
		SpecialKind        special_kind;
	};

	class DVMValue {
		using StoredValueVariant
			= std::variant<DVMPlace, DVMImmediate, DVMLabel, DVMFunctionName, DVMExternCFunctionName>;

		StoredValueVariant stored_value;

	public:
		DVMValue(StoredValueVariant value): stored_value(std::move(value)) {}

		bool operator==(const DVMValue& other) const = default;

		operator vm::opargs::OpCodeArg() const;

		[[nodiscard]] vm::code::TypeExpr getTypeExpr() const;

		/**
		 * @brief Converts the DVMValue into it's typed argument representation.
		 */
		[[nodiscard]] vm::opargs::OpCodeArg asArgument() const;

		/**
		 * @brief Converts the DVMValue into it's untyped argument representation(`pany`). Should be
		 * used only when working with `store_X_X`, `load_X_X`, `ref_X_X` instructions. Panics if
		 * the DVMValue can't be converted into an any argument, e.g. Is an Immediate, Label or a
		 * Function.
		 */
		[[nodiscard]] vm::opargs::OpCodeArg asAnyArgument() const;

		template<class T>
		[[nodiscard]] bool is() const {
			return std::holds_alternative<T>(stored_value);
		}

		template<class T>
		[[nodiscard]] T get() const {
			return std::get<T>(stored_value);
		}
	};
