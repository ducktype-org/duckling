		constexpr std::string_view DEFAULT_VERSION = "0.1.0";

		void info(const std::string& message) { std::cerr << "info: " << message << "\n"; }

		void warning(const std::string& message) { std::cerr << "warning: " << message << "\n"; }

		int fail(const std::string& message) {
			std::cerr << "error: " << message << "\n";
			return 1;
		}

		std::vector<std::string> banner(const Recipe& recipe, const Resolved& resolved) {
			std::string from;
			for (const auto& header: recipe.headers) from += (from.empty() ? "" : ", ") + header;
			if (!resolved.versions.empty()) {
				std::string versions;
				for (const auto& [package, version]: resolved.versions)
					versions
						+= std::format("{}{} {}", versions.empty() ? "" : ", ", package, version);
				from += std::format(" ({})", versions);
			}
			return {
				std::format("Generated by `duckbind` from {}.", from),
				std::format("Do not edit: change `{}` and run `duckbind regen`.", RECIPE_FILE),
			};
		}

		/**
		 * @brief The clang arguments for `resolved`, with the recipe's relative paths (headers and
		 * `-I` directories) made absolute against the package's `root`.
		 */
		GenerateOptions generateOptions(
			const Recipe&                recipe,
			const Resolved&              resolved,
			const std::filesystem::path& root,
			const std::string&           name
		) {
			GenerateOptions options;
			std::error_code ec;
			for (const auto& header: recipe.headers) {
				auto path = root / header;
				options.read.headers.push_back(
					std::filesystem::is_regular_file(path, ec) ? path.lexically_normal().string()
															   : header
				);
			}
			for (const auto& flag: resolved.cflags)
				if (flag.starts_with("-I") && flag.size() > 2 && flag[2] != '/')
					options.read.clang_args.push_back(
						"-I" + (root / flag.substr(2)).lexically_normal().string()
					);
				else
					options.read.clang_args.push_back(flag);
			options.lower.include   = recipe.include;
			options.lower.exclude   = recipe.exclude;
			options.bindings_import = std::format("{0}.{1}.{0}", name, GENERATED_DIR);
			options.banner          = banner(recipe, resolved);
			return options;
		}

		/// The files of `src/generated/` the recipe gives, by name, plus the layout check.
		struct Output final {
			std::map<std::string, std::string> files;
			Generated                          generated;
		};

		std::expected<Output, std::string> translate(
			const Recipe&                recipe,
			const Resolved&              resolved,
			const std::filesystem::path& root,
			const std::string&           name
		) {
			auto   options = generateOptions(recipe, resolved, root, name);
			Output output;
			output.generated = generate(options);
			if (const auto& errors = output.generated.errors; !errors.empty()) {
				std::string shown;
				for (const auto& error: errors | std::views::take(20)) shown += "\n" + error;
				if (errors.size() > 20)
					shown += std::format("\n... and {} more", errors.size() - 20);
				return std::unexpected("the headers do not compile:" + shown);
			}
			output.files[name + ".dk"]                        = output.generated.bindings;
			output.files[std::format("{}.dk", GENERATED_DIR)] = generatedRootModule(options.banner);
			return output;
		}

		std::expected<Recipe, std::string> readRecipe(const PackagePaths& paths) {
			auto text = readFile(paths.recipe());
			if (!text)
				return std::unexpected(std::format(
					"cannot read `{}`; create the package with `duckbind new`",
					paths.recipe().string()
				));
			auto recipe = parseRecipe(*text);
			if (!recipe)
				return std::unexpected(std::format(
					"`{}` is not a valid recipe: {}", paths.recipe().string(), recipe.error()
				));
			return recipe;
		}

		std::expected<std::string, std::string> readName(const PackagePaths& paths) {
			auto text = readFile(paths.manifest());
			if (!text) return std::unexpected(text.error());
			auto name = manifestName(*text);
			if (!name)
				return std::unexpected(
					std::format("`{}`: {}", paths.manifest().string(), name.error())
				);
			return name;
		}

		/// Translates the headers and replaces `src/generated/` with the result.
		std::expected<Generated, std::string> generatePackage(
			const PackagePaths& paths,
			const std::string&  name,
			const Recipe&       recipe,
			const Resolved&     resolved
		) {
			auto output = translate(recipe, resolved, paths.root, name);
			if (!output) return std::unexpected(output.error());

			std::error_code ec;
			std::filesystem::remove_all(paths.generated(), ec);
			for (const auto& [file, content]: output->files)
				if (auto written = writeFile(paths.generated() / file, content); !written)
					return std::unexpected(written.error());
			if (!std::filesystem::exists(paths.src() / "src.dk", ec))
				if (auto written = writeFile(paths.src() / "src.dk", rootModule(name)); !written)
					return std::unexpected(written.error());

			const auto& module = output->generated.module;
			info(std::format(
				"generated `{}`: {} classes, {} functions, {} constants",
				name,
				module.classes.size(),
				module.fundecls.size(),
				module.constants.size()
			));
			if (!module.skipped.empty())
				info(std::format(
					"skipped {} declarations; the reasons are listed at the top of `{}`",
					module.skipped.size(),
					(paths.generated() / (name + ".dk")).string()
				));
			for (const auto& message: resolved.warnings) warning(message);
			return std::move(output->generated);
		}

		std::expected<void, std::string> finish(
			const PackagePaths& paths,
			const std::string&  name,
			const Resolved&     resolved,
			const Generated&    generated,
			bool                verify_package,
			const std::string&  duck
		) {
			if (!verify_package) return {};
			// @TODO: #4144 check on the DVM too once `external-libs` work there.
			const bool dvm = resolved.external_libs.empty();
			if (!dvm) info("not checking on the DVM, which does not load `external-libs` yet");
			VerifyOptions options{ .package_root = paths.root,
				                   .name         = name,
				                   .layout_check = generated.layout_check,
				                   .layouts      = {},
				                   .duck         = duck,
				                   .native       = true,
				                   .dvm          = dvm };
			for (const auto& layout: generated.module.layouts)
				options.layouts.push_back(layout.name);
			if (auto checked = verify(options, info); !checked) return checked;
			info("the package builds, links and matches the C layouts");
			return {};
		}

		std::filesystem::path normalAbsolute(const std::filesystem::path& path) {
			return std::filesystem::absolute(path).lexically_normal();
		}

