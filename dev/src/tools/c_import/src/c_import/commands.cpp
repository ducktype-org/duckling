	std::string packageNameError(const std::string& name) {
		const bool identifier
			= !name.empty() && std::isalpha(static_cast<unsigned char>(name.front())) != 0
		   && std::ranges::all_of(name, [](char c) {
				  return std::isalnum(static_cast<unsigned char>(c)) != 0 || c == '_';
			  });
		if (!identifier || isReservedName(name))
			return std::format(
				"`{}` has to be a valid Duckling identifier, since it is the import path", name
			);
		if (name == GENERATED_DIR)
			return std::format(
				"`{}` is the name of a generated module; pick another package name", name
			);
		return {};
	}

	bool isPlainVersion(std::string_view version) {
		std::size_t parts = 0;
		for (auto part: std::views::split(version, '.')) {
			++parts;
			if (std::ranges::empty(part) || !std::ranges::all_of(part, [](char c) {
					return std::isdigit(static_cast<unsigned char>(c)) != 0;
				}))
				return false;
		}
		return parts == 3;
	}

	int newPackage(NewOptions options) {
		PackagePaths    paths{ normalAbsolute(options.at) };
		std::error_code ec;
		for (const auto& existing: { paths.manifest(), paths.recipe() })
			if (std::filesystem::exists(existing, ec))
				return fail(std::format(
					"`{}` already exists; use `duckbind regen` to regenerate the package",
					existing.string()
				));
		auto name = options.name.value_or(paths.root.filename().string());
		if (auto error = packageNameError(name); !error.empty())
			return fail(error + (options.name ? "" : "; pass `--name`"));
		if (options.recipe.headers.empty()) return fail("no headers given; pass `--header`");
		relativize(options.recipe, std::filesystem::current_path(), paths.root);

		const bool created_root = !std::filesystem::exists(paths.root, ec);
		auto       result       = [&]() -> std::expected<void, std::string> {
            std::filesystem::create_directories(paths.root, ec);
            if (ec)
                return std::unexpected(
                    std::format("cannot create `{}`: {}", paths.root.string(), ec.message())
                );
            auto resolved = resolve(options.recipe, paths.root);
            if (!resolved) return std::unexpected(resolved.error());
            auto version = std::string{ DEFAULT_VERSION };
            if (!resolved->versions.empty() && isPlainVersion(resolved->versions.front().second))
                version = resolved->versions.front().second;
            auto generated = generatePackage(paths, name, options.recipe, *resolved);
            if (!generated) return std::unexpected(generated.error());
            if (auto written = writeFile(paths.recipe(), recipeText(options.recipe)); !written)
                return written;
            if (auto written = writeFile(paths.manifest(), newManifest(name, version, *resolved));
                !written)
                return written;
            return finish(paths, name, *resolved, *generated, options.verify, options.duck);
		}();
		if (!result) {
			if (created_root && !std::filesystem::exists(paths.manifest(), ec))
				std::filesystem::remove_all(paths.root, ec);
			return fail(result.error());
		}
		return 0;
	}

	int regenPackage(const std::filesystem::path& at, bool verify_package, const std::string& duck) {
		PackagePaths paths{ normalAbsolute(at) };
		auto         recipe = readRecipe(paths);
		if (!recipe) return fail(recipe.error());
		auto name = readName(paths);
		if (!name) return fail(name.error());
		auto resolved = resolve(*recipe, paths.root);
		if (!resolved) return fail(resolved.error());
		auto generated = generatePackage(paths, *name, *recipe, *resolved);
		if (!generated) return fail(generated.error());

		auto manifest = readFile(paths.manifest());
		if (!manifest) return fail(manifest.error());
		auto updated = withLibraryKeys(*manifest, *resolved);
		if (!updated)
			return fail(std::format("`{}`: {}", paths.manifest().string(), updated.error()));
		if (*updated != *manifest)
			if (auto written = writeFile(paths.manifest(), *updated); !written)
				return fail(written.error());

		if (auto finished = finish(paths, *name, *resolved, *generated, verify_package, duck);
		    !finished)
			return fail(finished.error());
		return 0;
	}

	int checkPackage(const std::filesystem::path& at) {
		PackagePaths paths{ normalAbsolute(at) };
		auto         recipe = readRecipe(paths);
		if (!recipe) return fail(recipe.error());
		auto name = readName(paths);
		if (!name) return fail(name.error());
		auto resolved = resolve(*recipe, paths.root);
		if (!resolved) return fail(resolved.error());
		auto expected = translate(*recipe, *resolved, paths.root, *name);
		if (!expected) return fail(expected.error());

		std::map<std::string, std::string> actual;
		std::error_code                    ec;
		for (const auto& entry: std::filesystem::directory_iterator(paths.generated(), ec))
			if (auto text = readFile(entry.path()))
				actual[entry.path().filename().string()] = *text;

		std::vector<std::string> differences;
		for (const auto& [file, content]: expected->files) {
			auto found = actual.find(file);
			if (found == actual.end())
				differences.push_back(std::format("`{}` is missing", file));
			else if (found->second != content)
				differences.push_back(std::format("`{}` differs", file));
		}
		for (const auto& file: actual | std::views::keys)
			if (!expected->files.contains(file))
				differences.push_back(std::format("`{}` is not generated by the recipe", file));

		auto manifest = readFile(paths.manifest());
		if (!manifest) return fail(manifest.error());
		auto libraries = manifestLibraries(*manifest);
		if (!libraries) return fail(libraries.error());
		auto list = [](const std::vector<std::string>& values) {
			std::string text;
			for (const auto& value: values) text += (text.empty() ? "" : ", ") + value;
			return "[" + text + "]";
		};
		if (libraries->external_libs != resolved->external_libs)
			differences.push_back(std::format(
				"`metadata.external-libs` is {}, the recipe gives {}",
				list(libraries->external_libs),
				list(resolved->external_libs)
			));
		if (libraries->external_lib_paths != resolved->external_lib_paths)
			differences.push_back(std::format(
				"`metadata.external-lib-paths` is {}, the recipe gives {}",
				list(libraries->external_lib_paths),
				list(resolved->external_lib_paths)
			));

		if (!differences.empty()) {
			std::string text;
			for (const auto& difference: differences) text += "\n  " + difference;
			return fail(std::format(
				"the package is out of date with `{}`; run `duckbind regen`:{}", RECIPE_FILE, text
			));
		}
		info(std::format("`{}` is up to date with `{}`", *name, RECIPE_FILE));
		return 0;
	}

	int writeBindings(
		const std::filesystem::path&      recipe_file,
		const std::filesystem::path&      out,
		const std::optional<std::string>& name
	) {
		auto text = readFile(recipe_file);
		if (!text) return fail(text.error());
		auto recipe = parseRecipe(*text);
		if (!recipe)
			return fail(
				std::format("`{}` is not a valid recipe: {}", recipe_file.string(), recipe.error())
			);
		const auto root        = normalAbsolute(recipe_file).parent_path();
		const auto module_name = name.value_or(root.filename().string());
		if (auto error = packageNameError(module_name); !error.empty())
			return fail(error + (name ? "" : "; pass `--name`"));
		auto resolved = resolve(*recipe, root);
		if (!resolved) return fail(resolved.error());
		auto output = translate(*recipe, *resolved, root, module_name);
		if (!output) return fail(output.error());
		for (const auto& [file, content]: output->files)
			if (auto written = writeFile(out / file, content); !written)
				return fail(written.error());
		for (const auto& message: resolved->warnings) warning(message);
		return 0;
	}

